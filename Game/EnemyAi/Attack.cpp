#include "pch.h"
#include "Game/EnemyAi/Attack.h"

//-------------------------------------------------------------------
// コンストラクタ
//-------------------------------------------------------------------
Attack::Attack()
	:
	m_tank{}
{
}
//-------------------------------------------------------------------
// 初期化処理
//-------------------------------------------------------------------
void Attack::Initialize(Tank* tank)
{
	m_tank = tank;
}

//-------------------------------------------------------------------
// 更新処理
//-------------------------------------------------------------------
void Attack::Update(float elapsedTime)
{
	// 射撃処理
	m_tank->GetCannon()->StartReload();
	m_tank->GetCannon()->Shoot();
}